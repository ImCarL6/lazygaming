import assert from 'node:assert/strict';
import vm from 'node:vm';
import { readFileSync } from 'node:fs';
const ctx = {}; vm.createContext(ctx); vm.runInContext(readFileSync('tv/stream-policy.js','utf8'),ctx);
const profile = ctx.LGStreamPolicy.profile;
assert.equal(profile({width:2560,height:1440},{}).width,2560);
assert.equal(profile({width:2560,height:1440},{}).bitrate,20);
assert.equal(profile({width:2560,height:1440},{resolution:'3840x2160'}).width,2560,'4K não inventa detalhe de origem1440p');
assert.equal(profile({width:3840,height:2160},{},{width:1920,height:1080}).height,1080,'respeita limite do decoder');
assert.equal(profile({width:2560,height:1440},{resolution:'1920x1080',fps:30,bitrate:20}).fps,30);
assert.throws(()=>profile({width:2560,height:1440},{bitrate:150}));
assert.throws(()=>profile(null,{}));
const policy = ctx.LGStreamPolicy;
assert.equal(policy.adaptive({}), true);
assert.equal(policy.adaptive({bitrate:10}), false, 'bitrate manual não é sobrescrito');
assert.equal(policy.adaptive({adaptive:false}), false);
let quality = profile({width:3840,height:2160},{});
assert.equal(quality.bitrate,25);
const guard = new policy.Guard(); guard.reset(1000);
guard.warning('Slow connection to PC. Reduce your bitrate',31000);
assert.equal(guard.next(quality,35000),null,'aviso passageiro não reconecta');
guard.warning('',36000); assert.equal(guard.next(quality,40000),null,'recuperação cancela redução');
guard.warning('Slow connection to PC. Reduce your bitrate',41000);
quality = guard.next(quality,48000); assert.equal(quality.bitrate,20);
assert.equal(guard.next(quality,90000),null,'sem novo aviso não continuar reduzindo');
for(let i=0;i<12;i++) { const reduced=policy.reduce(quality); if(!reduced) break; assert.ok(reduced.width<=quality.width && reduced.height<=quality.height && reduced.fps<=quality.fps); quality=reduced; }
assert.equal(quality.height,1080); assert.equal(quality.bitrate,6); assert.equal(quality.fps,30);
assert.equal(policy.reduce(quality),null,'limite impede ciclo infinito');
const engine=readFileSync('tv/stream-engine/engine.js','utf8');
assert.ok(!engine.includes('quitApp('),'desconectar não encerra app/jogo');
assert.ok(engine.includes('event.source !== parent'),'comandos só da página proprietária');
assert.ok(!engine.includes('requestAnimationFrame'),'sem cópia de frames por JS');
console.log('PASS: resolução real, limiteTV, bitrate, desconexão sem encerrar jogo e canal privado.');
